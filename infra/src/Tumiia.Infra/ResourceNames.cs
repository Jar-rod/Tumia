namespace Tumiia.Infra;

/// <summary>
/// The fixed names of the resources the deploy workflow touches. Kept in one place so the stacks and
/// <c>.github/workflows/deploy.yml</c> agree. Every name starts with the environment ("prod-...").
/// </summary>
public sealed class ResourceNames(string environmentName, string account)
{
    /// <summary>The container name inside the API task definition.</summary>
    public const string ContainerName = "api";

    /// <summary>The header CloudFront adds so the API can tell a request came through CloudFront.</summary>
    public const string OriginVerifyHeader = "X-Origin-Verify";

    /// <summary>Names a CloudFormation stack, for example <c>prod-tumiia-app</c>.</summary>
    public string Stack(string part) => $"{environmentName}-tumiia-{part}";

    public string ClusterName => $"{environmentName}-tumiia";

    public string ServiceName => $"{environmentName}-tumiia-api";

    public string RepositoryName => $"{environmentName}-tumiia-api";

    public string TaskFamily => $"{environmentName}-tumiia-api";

    public string LogGroupName => $"/ecs/{environmentName}-tumiia-api";

    public string TaskRoleName => $"{environmentName}-tumiia-api-task";

    public string ExecutionRoleName => $"{environmentName}-tumiia-api-execution";

    public string DeployRoleName => $"{environmentName}-tumiia-github-deploy";

    /// <summary>S3 bucket names are global, so the account id keeps them unique.</summary>
    public string DocumentsBucketName => $"{environmentName}-tumiia-documents-{account}";

    public string WebBucketName => $"{environmentName}-tumiia-web-{account}";

    public string QueueName => $"{environmentName}-document-analysis";

    public string DeadLetterQueueName => $"{environmentName}-document-analysis-dlq";

    public string DatabaseSecretName => $"{environmentName}/tumiia/database";

    /// <summary>Created by hand as an SSM SecureString (CloudFormation cannot create SecureStrings).</summary>
    public string JwtSigningKeyParameterName => $"/{environmentName}/tumiia/jwt-signing-key";

    /// <summary>Generated by CDK in Secrets Manager, so CloudFront and the API can both read it.</summary>
    public string OriginVerifySecretName => $"{environmentName}/tumiia/origin-verify";

    /// <summary>The address CloudFront uses to reach the load balancer, for example <c>origin.app.example.co.za</c>.</summary>
    public static string OriginHostName(string domainName) => $"origin.{domainName}";
}
